# Python has methods that check what kind of characters
# are inside a string.
#
# isalpha()  -> only letters
# isdigit()  -> only numbers
# isalnum()  -> letters and/or numbers
# isspace()  -> only spaces

print("Hello".isalpha())
print("12345".isdigit())
print("Hello123".isalnum())
print("   ".isspace())
